/**
 * build-seo.js — generates everything search engines need. Run:  npm run build:seo
 *
 * 1. <head> metadata for every page: title, description, canonical, robots,
 *    Open Graph + Twitter cards (link previews), verification tags, JSON-LD.
 * 2. A pre-rendered, crawlable HTML page for EVERY project (project-<id>.html).
 *    Without this, project content only existed after JavaScript ran.
 * 3. Pre-rendered HTML for the home page sections and the gallery (JS still upgrades them).
 * 4. sitemap.xml, robots.txt and site.webmanifest.
 *
 * Generated regions are wrapped in <!-- seo:start --> / <!-- prerender:x --> markers,
 * so the script can be re-run safely any time content changes.
 */
import { readFileSync, writeFileSync, readdirSync, unlinkSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as C from './seo.config.js';
import { projects, CATEGORY_LABEL, STATUS_LABEL } from '../public/js/data/projects.js';
import { featuredIds, capabilities, process as steps, caseStudies, experience, faq, tech } from '../public/js/data/home.js';

const PUB = join(dirname(fileURLToPath(import.meta.url)), '../public');
const TODAY = new Date().toISOString().slice(0, 10);
const abs = (path = '') => new URL(path, C.SITE_URL).href;
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const projectFile = (p) => `project-${p.id}.html`;
const read = (f) => readFileSync(join(PUB, f), 'utf8');
const write = (f, s) => writeFileSync(join(PUB, f), s);

// ------------------------------------------------------------------ structured data
const PERSON_ID = abs('#person');
const WEBSITE_ID = abs('#website');
const person = () => ({
  '@type': 'Person', '@id': PERSON_ID, name: C.PERSON.name, url: abs(), image: abs(C.PERSON.image),
  jobTitle: C.PERSON.jobTitle, description: C.PERSON.description, email: `mailto:${C.PERSON.email}`,
  address: { '@type': 'PostalAddress', addressLocality: C.PERSON.locality, addressRegion: C.PERSON.region, addressCountry: C.PERSON.country },
  affiliation: { '@type': 'CollegeOrUniversity', name: C.PERSON.school },
  knowsAbout: C.PERSON.knowsAbout, sameAs: C.PERSON.sameAs,
});
const website = () => ({ '@type': 'WebSite', '@id': WEBSITE_ID, url: abs(), name: C.SITE_NAME, inLanguage: 'en', publisher: { '@id': PERSON_ID } });
const crumbs = (items) => ({
  '@type': 'BreadcrumbList',
  itemListElement: [{ name: 'Home', url: abs() }, ...items].map((it, i) => ({ '@type': 'ListItem', position: i + 1, name: it.name, item: it.url })),
});
const ld = (nodes) => `<script type="application/ld+json">${JSON.stringify({ '@context': 'https://schema.org', '@graph': nodes }).replace(/</g, '\\u003c')}</script>`;

function schemaFor(file, m) {
  const url = abs(file === 'index.html' ? '' : file);
  if (file === 'index.html') {
    return [person(), website(), { '@type': 'ProfilePage', '@id': `${url}#page`, url, name: m.title, description: m.description, isPartOf: { '@id': WEBSITE_ID }, mainEntity: { '@id': PERSON_ID }, dateModified: TODAY }];
  }
  if (file === 'projects.html') {
    return [{ '@type': 'CollectionPage', url, name: m.title, description: m.description, isPartOf: { '@id': WEBSITE_ID }, author: { '@id': PERSON_ID },
      mainEntity: { '@type': 'ItemList', numberOfItems: projects.length, itemListElement: projects.map((p, i) => ({ '@type': 'ListItem', position: i + 1, url: abs(projectFile(p)), name: p.title })) } },
    crumbs([{ name: m.crumb, url }])];
  }
  const nodes = [crumbs([{ name: m.crumb ?? m.title, url }])];
  if (m.schema === 'Article') nodes.push({ '@type': 'Article', headline: m.headline, description: m.description, url, image: abs(C.OG_IMAGE), author: { '@id': PERSON_ID }, publisher: { '@id': PERSON_ID }, dateModified: TODAY, mainEntityOfPage: url });
  if (m.schema === 'ContactPage') nodes.push({ '@type': 'ContactPage', url, name: m.title, description: m.description, mainEntity: { '@id': PERSON_ID } });
  if (m.app) nodes.push({ '@type': 'WebApplication', name: m.crumb, url, description: m.description, applicationCategory: 'DeveloperApplication', operatingSystem: 'Any (web browser)', author: { '@id': PERSON_ID }, isAccessibleForFree: true });
  return nodes;
}

// ------------------------------------------------------------------ <head> block
function headBlock(file, m, graph) {
  const url = abs(file === 'index.html' ? '' : file);
  const indexable = m.index !== false;
  const img = abs(m.image ?? C.OG_IMAGE);
  return [
    '<!-- seo:start — generated by scripts/build-seo.js (edit scripts/seo.config.js) -->',
    `<title>${esc(m.title)}</title>`,
    `<meta name="description" content="${esc(m.description)}">`,
    `<meta name="robots" content="${indexable ? 'index, follow, max-image-preview:large, max-snippet:-1' : 'noindex, follow'}">`,
    indexable ? `<link rel="canonical" href="${url}">` : '',
    `<meta name="author" content="${esc(C.PERSON.name)}">`,
    `<meta property="og:type" content="${m.type ?? (m.schema === 'Article' ? 'article' : 'website')}">`,
    `<meta property="og:site_name" content="${esc(C.SITE_NAME)}">`,
    `<meta property="og:locale" content="${C.LOCALE}">`,
    `<meta property="og:title" content="${esc(m.ogTitle ?? m.title)}">`,
    `<meta property="og:description" content="${esc(m.description)}">`,
    `<meta property="og:url" content="${url}">`,
    `<meta property="og:image" content="${img}">`,
    '<meta property="og:image:width" content="1200">',
    '<meta property="og:image:height" content="630">',
    `<meta property="og:image:alt" content="${esc(m.imageAlt ?? `${C.PERSON.name}, web designer and developer`)}">`,
    '<meta name="twitter:card" content="summary_large_image">',
    C.TWITTER_HANDLE ? `<meta name="twitter:site" content="${esc(C.TWITTER_HANDLE)}">` : '',
    `<meta name="twitter:title" content="${esc(m.ogTitle ?? m.title)}">`,
    `<meta name="twitter:description" content="${esc(m.description)}">`,
    `<meta name="twitter:image" content="${img}">`,
    C.GOOGLE_SITE_VERIFICATION ? `<meta name="google-site-verification" content="${esc(C.GOOGLE_SITE_VERIFICATION)}">` : '',
    C.BING_SITE_VERIFICATION ? `<meta name="msvalidate.01" content="${esc(C.BING_SITE_VERIFICATION)}">` : '',
    '<link rel="apple-touch-icon" href="assets/apple-touch-icon.png">',
    '<link rel="manifest" href="site.webmanifest">',
    graph?.length ? ld(graph) : '',
    '<!-- seo:end -->',
  ].filter(Boolean).map((l) => `  ${l}`).join('\n');
}

/** Replace any old title/description/og/twitter tags and the previous generated block. */
function injectHead(html, block) {
  html = html.replace(/\s*<!-- seo:start[\s\S]*?<!-- seo:end -->/, '');
  html = html.replace(/\s*<title>[\s\S]*?<\/title>/, '')
    .replace(/\s*<meta name="description"[^>]*>/g, '')
    .replace(/\s*<meta property="og:[^>]*>/g, '')
    .replace(/\s*<meta name="twitter:[^>]*>/g, '')
    .replace(/\s*<link rel="canonical"[^>]*>/g, '');
  return html.replace(/(<meta name="viewport"[^>]*>)/, `$1\n${block}`);
}

function setRegion(html, name, content) {
  const re = new RegExp(`<!-- prerender:${name} -->[\\s\\S]*?<!-- /prerender:${name} -->`);
  const region = `<!-- prerender:${name} -->${content}<!-- /prerender:${name} -->`;
  if (!re.test(html)) throw new Error(`missing prerender marker "${name}"`);
  return html.replace(re, region);
}

// ------------------------------------------------------------------ static snippets
const staticCard = (p) => `<article class="pcard pcard-static"><div class="pcard-body"><div class="pcard-labels"><span class="label ${p.status === 'live' ? 'live' : 'concept'}">${STATUS_LABEL[p.status]}</span><span class="pcard-cat">${CATEGORY_LABEL[p.category]}</span></div><h3><a class="pcard-link" href="${projectFile(p)}">${esc(p.title)}</a></h3><p class="pcard-summary">${esc(p.summary)}</p></div></article>`;

// ------------------------------------------------------------------ project pages
function projectPage(p, i) {
  const prev = projects[(i - 1 + projects.length) % projects.length];
  const next = projects[(i + 1) % projects.length];
  const file = projectFile(p);
  const isConcept = p.status !== 'live';
  const m = {
    // keep titles under ~65 characters so Google doesn't truncate them
    title: (() => {
      const short = { uiux: 'UI/UX Design', web: 'Web Design', fullstack: 'Full-Stack App', lab: 'JavaScript Tool' }[p.category];
      const full = `${p.title} — ${short} | ${C.PERSON.name}`;
      return full.length <= 65 ? full : `${p.title} | ${C.PERSON.name}`;
    })(),
    description: `${p.summary} ${STATUS_LABEL[p.status]} by ${C.PERSON.name}, web designer & developer.`.slice(0, 300),
  };
  const graph = [
    { '@type': 'CreativeWork', '@id': `${abs(file)}#work`, name: p.title, headline: p.title, description: p.summary, url: abs(file), image: abs(C.OG_IMAGE),
      genre: CATEGORY_LABEL[p.category], keywords: [CATEGORY_LABEL[p.category], ...p.tech].join(', '), creator: { '@id': PERSON_ID }, author: { '@id': PERSON_ID }, isPartOf: { '@id': WEBSITE_ID },
      ...(p.demo ? { workExample: { '@type': 'WebApplication', name: p.title, url: abs(p.demo), applicationCategory: 'WebApplication', operatingSystem: 'Any (web browser)' } } : {}) },
    crumbs([{ name: 'Work', url: abs('projects.html') }, { name: CATEGORY_LABEL[p.category], url: abs(`projects.html?filter=${p.category}`) }, { name: p.title, url: abs(file) }]),
  ];
  const mail = `mailto:${C.PERSON.email}?subject=${encodeURIComponent(`About: ${p.title}`)}`;
  const related = projects.filter((x) => x.category === p.category && x.id !== p.id).slice(0, 3);
  const platform = { mobile: 'Mobile app', web: 'Website / web app', desktop: 'Desktop web app' }[p.platform];

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
${headBlock(file, m, graph)}
  <meta name="theme-color" content="#060709">
  <link rel="icon" href="assets/favicon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="css/base.css">
  <link rel="stylesheet" href="css/components.css">
  <link rel="stylesheet" href="css/mockups.css">
  <link rel="stylesheet" href="css/gallery.css">
  <script type="module" src="js/layout.js"></script>
  <script type="module" src="js/pages/project-static.js"></script>
</head>
<body data-section="work">
  <!-- Generated by scripts/build-seo.js from js/data/projects.js. Edit the data, then run: npm run build:seo -->
  <div id="site-header"></div>
  <main id="main" class="container">
    <div id="detail" data-project-id="${p.id}">
      <nav class="crumbs" aria-label="Breadcrumb"><a href="projects.html">Work</a> / <a href="projects.html?filter=${p.category}">${CATEGORY_LABEL[p.category]}</a> / <span aria-current="page">${esc(p.title)}</span></nav>
      <header class="detail-head">
        <div class="pcard-labels"><span class="label ${isConcept ? 'concept' : 'live'}">${STATUS_LABEL[p.status]}</span><span class="pcard-cat">${CATEGORY_LABEL[p.category]}</span></div>
        <h1>${esc(p.title)}</h1>
        <p class="lede">${esc(p.summary)}</p>
        <div class="detail-cta">
          ${p.demo ? `<a class="button" href="${p.demo}">Open live demo ↗</a>` : `<a class="button" href="${esc(mail)}">Discuss a similar project</a>`}
          <a class="button outline" href="projects.html">← All projects</a>
        </div>
      </header>
      <div class="detail-stage" data-tilt style="--accent-p: ${p.preview.theme.accent}"><div class="detail-mock" id="detail-mock" role="img" aria-label="Preview of ${esc(p.title)}"></div></div>
      <dl class="facts">
        <div><dt>Type</dt><dd>${STATUS_LABEL[p.status]}</dd></div>
        <div><dt>Category</dt><dd>${CATEGORY_LABEL[p.category]}</dd></div>
        <div><dt>Platform</dt><dd>${platform}</dd></div>
        <div><dt>${isConcept ? 'Proposed tools' : 'Built with'}</dt><dd>${esc(p.tech.join(' · '))}</dd></div>
      </dl>
      <div class="detail-grid">
        <section class="card"><span class="tag">THE PROBLEM</span><h2>Why it matters</h2><p>${esc(p.problem)}</p></section>
        <section class="card"><span class="tag">${isConcept ? 'DESIGN APPROACH' : 'HOW IT WAS BUILT'}</span><h2>Approach</h2><p>${esc(p.approach)}</p></section>
      </div>
      <section class="section">
        <h2 class="eyebrow">Key features</h2>
        <ul class="feature-list">${p.features.map((f, n) => `<li><span class="fnum">${String(n + 1).padStart(2, '0')}</span>${esc(f)}</li>`).join('')}</ul>
      </section>
      <section class="section">
        <h2 class="eyebrow">Interface palette</h2>
        <div class="palette-row">${Object.entries(p.preview.theme).map(([k, v]) => `<div class="swatch-chip"><i style="background:${v}"></i><span>${k}</span><code>${v}</code></div>`).join('')}</div>
      </section>
      <div class="callout"><p><strong>${isConcept ? 'Honest note: ' : 'Live demo: '}</strong>${isConcept
        ? 'this is a self-initiated concept to show design and planning skills. It is not client work and has not been built or launched.'
        : 'this project is built and working in this repository. It is a portfolio demo, not a commercial product, and it uses sample data.'}</p></div>
      <nav class="pager" aria-label="More projects">
        <a href="${projectFile(prev)}" class="pager-link"><span class="muted small">← Previous</span><strong>${esc(prev.title)}</strong></a>
        <a href="${projectFile(next)}" class="pager-link next"><span class="muted small">Next →</span><strong>${esc(next.title)}</strong></a>
      </nav>
      <section class="section"><p class="eyebrow">Related</p><h2>More in ${CATEGORY_LABEL[p.category]}</h2>
        <div class="bento compact" id="related">${related.map(staticCard).join('')}</div>
      </section>
    </div>
  </main>
  <footer id="site-footer"></footer>
</body>
</html>
`;
}

// ------------------------------------------------------------------ run
// 1) remove stale project pages (e.g. a project that was deleted from the data)
for (const f of readdirSync(PUB)) if (/^project-[a-z0-9-]+\.html$/.test(f)) unlinkSync(join(PUB, f));

// 2) one crawlable page per project
projects.forEach((p, i) => write(projectFile(p), projectPage(p, i)));

// 3) metadata for every hand-written page
for (const [file, m] of Object.entries(C.PAGES)) {
  if (!existsSync(join(PUB, file))) continue;
  let html = read(file);
  html = injectHead(html, headBlock(file, m, m.index === false ? [] : schemaFor(file, m)));
  if (file === 'projects.html') html = setRegion(html, 'gallery', projects.map(staticCard).join(''));
  if (file === 'index.html') {
    const byId = (id) => projects.find((p) => p.id === id);
    html = setRegion(html, 'featured', featuredIds.map(byId).map((p) => `<article class="feature-row"><div class="fr-copy"><h3><a href="${projectFile(p)}">${esc(p.title)}</a></h3><p>${esc(p.summary)}</p><ul>${p.features.slice(0, 3).map((f) => `<li>${esc(f)}</li>`).join('')}</ul></div></article>`).join(''));
    html = setRegion(html, 'websites', projects.filter((p) => p.category === 'web').map(staticCard).join(''));
    html = setRegion(html, 'fullstack', projects.filter((p) => p.category === 'fullstack').sort((a, b) => (b.status === 'live') - (a.status === 'live')).slice(0, 6).map(staticCard).join(''));
    html = setRegion(html, 'capabilities', capabilities.map((c) => `<article class="card cap"><h3>${esc(c.title)}</h3><p>${esc(c.text)}</p></article>`).join(''));
    html = setRegion(html, 'tech', tech.map((t) => `<li class="tech ${t.status}"><span>${esc(t.name)}</span></li>`).join(''));
    html = setRegion(html, 'process', steps.map((s, n) => `<li class="pstep"><div class="pnode"><span>${String(n + 1).padStart(2, '0')}</span></div><div class="card"><h3>${esc(s.step)}</h3><p>${esc(s.text)}</p></div></li>`).join(''));
    html = setRegion(html, 'cases', caseStudies.map((c) => `<a class="card case-card" href="${c.href}"><div class="case-body"><span class="tag">${esc(c.tag.toUpperCase())}</span><h3>${esc(c.title)}</h3><p>${esc(c.text)}</p></div></a>`).join(''));
    html = setRegion(html, 'experience', experience.filter((e) => !e.placeholder).map((e) => `<li class="tl-item"><div class="tl-period">${esc(e.period)}</div><div><h3>${esc(e.role)}</h3><div class="tl-org">${esc(e.org)}</div><p>${esc(e.text)}</p></div></li>`).join(''));
    html = setRegion(html, 'faq', faq.map((f, n) => `<details${n === 0 ? ' open' : ''}><summary>${esc(f.q)}</summary><p>${esc(f.a)}</p></details>`).join(''));
  }
  write(file, html);
}

// 4) sitemap.xml — only indexable pages + every project page
const urls = [
  ...Object.entries(C.PAGES).filter(([f, m]) => m.index !== false && existsSync(join(PUB, f)))
    .map(([f, m]) => ({ loc: abs(f === 'index.html' ? '' : f), priority: m.priority ?? 0.5, changefreq: m.changefreq ?? 'monthly' })),
  ...projects.map((p) => ({ loc: abs(projectFile(p)), priority: p.status === 'live' ? 0.7 : 0.6, changefreq: 'monthly' })),
];
write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((u) => `  <url><loc>${u.loc}</loc><lastmod>${TODAY}</lastmod><changefreq>${u.changefreq}</changefreq><priority>${u.priority.toFixed(1)}</priority></url>`).join('\n')}
</urlset>
`);

// 5) robots.txt (search engines read it at the domain root; it also documents the sitemap)
write('robots.txt', `User-agent: *\nAllow: /\nDisallow: /api/\n\nSitemap: ${abs('sitemap.xml')}\n`);

// 6) web app manifest
write('site.webmanifest', JSON.stringify({
  name: C.SITE_NAME, short_name: 'Liorgio', start_url: './', scope: './', display: 'standalone',
  background_color: '#060709', theme_color: '#060709', description: C.PERSON.description,
  icons: [{ src: 'assets/apple-touch-icon.png', sizes: '180x180', type: 'image/png' }, { src: 'assets/icon-512.png', sizes: '512x512', type: 'image/png' }],
}, null, 2));

console.log(`SEO build done: ${Object.keys(C.PAGES).length} pages, ${projects.length} project pages, ${urls.length} sitemap URLs.`);
